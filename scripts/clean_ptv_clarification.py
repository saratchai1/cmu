def iter_paragraphs(doc: Document):
    for paragraph in doc.paragraphs:
        yield paragraph
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    yield paragraph
    for section in doc.sections:
        for area in (section.header, section.footer):
            for paragraph in area.paragraphs:
                yield paragraph


def set_paragraph_text(paragraph, text: str) -> None:
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


def remove_paragraph(paragraph) -> None:
    element = paragraph._element
    element.getparent().remove(element)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input_docx", type=Path)
    parser.add_argument("output_docx", type=Path)
    args = parser.parse_args()

    doc = Document(args.input_docx)
    changed = 0
    removed = 0

    # Materialize first because removing nodes while iterating a live collection is unsafe.
    paragraphs = list(iter_paragraphs(doc))
    for paragraph in paragraphs:
        text = paragraph.text.strip()
        if text in REMOVE_WHOLE_PARAGRAPHS:
            remove_paragraph(paragraph)
            removed += 1
            continue
        replacement = REPLACEMENTS.get(text)
        if replacement is not None:
            set_paragraph_text(paragraph, replacement)
            changed += 1

    args.output_docx.parent.mkdir(parents=True, exist_ok=True)
    doc.save(args.output_docx)

    # Re-open and fail loudly if any targeted uncertainty wording survived.
    check = Document(args.output_docx)
    leftovers = []
    for paragraph in iter_paragraphs(check):
        text = paragraph.text.strip()
        if any(phrase in text for phrase in BANNED_UNCERTAINTY_PHRASES):
            leftovers.append(text)

    if leftovers:
        raise SystemExit(
            "Targeted uncertainty wording still present:\n- " + "\n- ".join(leftovers)
        )

    print(f"Wrote {args.output_docx}")
    print(f"Replaced paragraphs: {changed}")
    print(f"Removed paragraphs: {removed}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
